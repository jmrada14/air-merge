"""
Build the QR code Air Merge shows on its "Get Air Merge" screen.

The badge draws the code from rectangles instead of loading a PNG, so it needs
no asset file and renders in the desktop simulator too. This writes the module
matrix into app/am_ui.py between the QR markers, one int per row with the
leftmost module in the highest bit.

  pip install segno
  python3 -I tools/qr_code.py
"""

import os
import sys

import segno

URL = "https://github.com/jmrada14/air-merge"
START = "# --- QR code (generated by tools/qr_code.py) ---\n"
END = "# --- end QR code ---\n"

HERE = os.path.dirname(os.path.abspath(__file__))
UI = os.path.join(HERE, "..", "app", "am_ui.py")


def block():
    qr = segno.make(URL, error="m", micro=False)
    rows = []
    for row in qr.matrix:
        value = 0
        for dark in row:
            value = value << 1 | (1 if dark else 0)
        rows.append(value)
    lines = [START, 'QR_URL = "%s"\n' % URL, "QR_SIZE = %d\n" % len(rows), "QR_ROWS = (\n"]
    lines += ["    0x%08x,\n" % value for value in rows]
    lines += [")\n", END]
    return "".join(lines), qr.version


def main():
    with open(UI) as f:
        source = f.read()
    start, end = source.find(START), source.find(END)
    if start < 0 or end < start:
        sys.exit("QR markers not found in %s" % UI)
    text, version = block()
    with open(UI, "w") as f:
        f.write(source[:start] + text + source[end + len(END):])
    print("QR version %d written to app/am_ui.py" % version)


if __name__ == "__main__":
    main()
