def draw(a, now):
    s = a.state
    background()
    if s == NOLINK:
        _nolink(a)
    elif s == LOBBY:
        _lobby(a, now)
    elif s == PAIRED:
        _list(a, now)
    elif s == CONFIRM_SEND:
        _confirm(a, now)
    elif s in SENDER:
        _out(a, now)
    elif s == OFFER_IN:
        _ask(a, now)
    elif s == OFFER_BAD:
        _bad(a, now)
    elif s in RECEIVER:
        _in(a, now)
    elif s == DONE:
        _result(a, now)
    elif s == SHARE:
        _share(a, now)


