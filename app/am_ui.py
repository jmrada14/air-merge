def _lobby(a, now):
    k = K()
    h = _title(10)
    ctext("Share apps badge to badge", WIDTH / 2, 16 + h, FONT_SMALL, k["muted"])

    panel(16, 48, WIDTH - 32, 38, k["panel"])
    identicon(a, a.my_id, 26, 55, 24)
    name = fit(a.my_name, FONT_BODY, 200)
    nw, nh = measure(name, FONT_BODY)
    text(name, 60, 56, FONT_BODY, k["text"])
    text("%d apps ready to share" % len(a.apps), 60, 58 + nh + 2, FONT_SMALL, k["muted"])

    prox = a.proximity
    status = "hold badges back to back"
    pen = k["text"]
    mode = 0
    progress = 0.0
    try:
        if prox.cooling(now) is not None:
            status = "pull apart"
            pen = k["gold"]
            mode = 1
        else:
            peer = prox.syncing()
            if peer is not None:
                progress = prox.progress(now)
                mode = 2
                if progress >= 1.0:
                    status = "connecting..."
                else:
                    status = "syncing with %s" % (peer.name or "badge")
                pen = k["green"]
    except Exception:
        pass
    ctext(fit(status, FONT_BODY, 290), WIDTH / 2, 96, FONT_BODY, pen)
    if mode == 2:
        bar(40, 112, WIDTH - 80, 5, progress, k["green"], k["line"])
    try:
        if mode == 1:
            a.pairing.draw_apart()
        elif mode == 2:
            a.pairing.draw_together(now)
        else:
            a.pairing.draw_loop(now)
    except Exception:
        pass
    toast(a, now, 198)
    hints((("get Air Merge", "ENTER"), ("exit", "BACK")))


_qr_runs = []


def qr_runs():
    """(x, y, length) of each horizontal run of dark modules, worked out once."""
    if not _qr_runs:
        for y, row in enumerate(QR_ROWS):
            x = 0
            while x < QR_SIZE:
                if row >> (QR_SIZE - 1 - x) & 1:
                    start = x
                    while x < QR_SIZE and row >> (QR_SIZE - 1 - x) & 1:
                        x += 1
                    _qr_runs.append((start, y, x - start))
                else:
                    x += 1
    return _qr_runs


def _share(a, now):
    k = K()
    # 5 px modules with a two module quiet zone, on a white card above the hints
    m = 5
    card = (QR_SIZE + 4) * m
    x, y = 12, (HEIGHT - 26 - card) // 2
    panel(x - 3, y - 3, card + 6, card + 6, k["purple"])
    panel(x, y, card, card, k["white"])
    screen.pen = k["black"]
    ox, oy = x + 2 * m, y + 2 * m
    for qx, qy, n in qr_runs():
        screen.rectangle(ox + qx * m, oy + qy * m, n * m, m)

    left = x + card + 14
    width = WIDTH - left - 8
    ty = 34
    merge_glyph(left, ty, k["purple_l"])
    text("Get it", left + 20, ty + 1, FONT_BODY, k["text"])
    ty += 30
    lh = measure("Ag", FONT_SMALL)[1] + 4
    for line in ("Scan to put Air Merge on your badge.",
                 "The repo has a one-line installer.",
                 "Then hold badges back to back to share apps."):
        for part in wrap(line, FONT_SMALL, width, 3):
            text(part, left, ty, FONT_SMALL, k["muted"])
            ty += lh
        ty += 6
    for part in ("github.com/", "jmrada14/air-merge"):
        text(fit(part, FONT_SMALL, width), left, ty, FONT_SMALL, k["purple_l"])
        ty += lh
    hints((("back", "BACK"),))


def _list(a, now):
    k = K()
    header(a)
    apps = a.apps
    who = fit(a.partner_name, FONT_BODY, 150)
    text("Send an app to " + who, 12, 33, FONT_BODY, k["text"])
    rtext("%d apps" % len(apps), WIDTH - 12, 34, FONT_SMALL, k["dim"])
    if not apps:
        ctext("No apps to share yet", WIDTH / 2, 110, FONT_BODY, k["muted"])
    top = a.top
    for row in range(ROWS):
        i = top + row
        if i >= len(apps):
            break
        app = apps[i]
        y = LIST_Y + row * ROW_H
        sel = i == a.sel
        if sel:
            panel(8, y, WIDTH - 22, ROW_H - 3, k["purple"])
        else:
            panel(8, y, WIDTH - 22, ROW_H - 3, k["panel"])
        info = fmt_app(app["size"], app["files"])
        iw, ih = measure(info, FONT_SMALL)
        name = app["name"]
        if app["slug"] == "air_merge":
            name += " (this app)"
        name = fit(name, FONT_BODY, WIDTH - 60 - iw)
        nw, nh = measure(name, FONT_BODY)
        cy = y + (ROW_H - 3) / 2
        text(name, 18, cy - nh / 2, FONT_BODY, k["text"])
        text(info, WIDTH - 22 - iw, cy - ih / 2, FONT_SMALL, k["text"] if sel else k["muted"])
    # scrollbar
    n = len(apps)
    if n > ROWS:
        track = ROWS * ROW_H - 3
        screen.pen = k["panel"]
        screen.rectangle(WIDTH - 9, LIST_Y, 3, track)
        th = max(10, track * ROWS / n)
        ty = LIST_Y + (track - th) * top / (n - ROWS)
        screen.pen = k["purple_l"]
        screen.rectangle(WIDTH - 9, ty, 3, th)
    if not toast(a, now, 208):
        ctext(fit("%s can send you one too" % a.partner_name, FONT_SMALL, 280), WIDTH / 2, 208,
              FONT_SMALL, k["dim"])
    if apps:
        hints((("send", "ENTER"), ("leave", "BACK")))
    else:
        hints((("leave", "BACK"),))


